import { contextBridge, ipcRenderer } from 'electron';

contextBridge.exposeInMainWorld('patchday', {
  state: () => ipcRenderer.invoke('state'),
  saveSettings: (patch: unknown) => ipcRenderer.invoke('settings', patch),
  check: () => ipcRenderer.invoke('check'),
  update: (force?: string[]) => ipcRenderer.invoke('update', force),
  updateNow: (keys: string[]) => ipcRenderer.invoke('update-now', keys),
  saveToken: (token: string) => ipcRenderer.invoke('token', token),
  saveAdminPassword: (password: string) => ipcRenderer.invoke('admin-password', password),
  forgetAdminPassword: () => ipcRenderer.invoke('admin-password-forget'),
  coffee: () => ipcRenderer.invoke('coffee'),
  checkSelf: () => ipcRenderer.invoke('self-check'),
  manualCheckSelf: () => ipcRenderer.invoke('self-check-manual'),
  installSelf: () => ipcRenderer.invoke('self-install'),
  onSelfProgress: (listener: (percent: number) => void) => ipcRenderer.on('self-progress', (_event, percent) => listener(percent)),
  onSelfAvailable: (listener: (version: string) => void) => ipcRenderer.on('self-available', (_event, version) => listener(version)),
  setupAdmin: () => ipcRenderer.invoke('admin'),
  onProgress: (listener: (items: unknown[]) => void) => ipcRenderer.on('progress', (_event, items) => listener(items)),
  onLog: (listener: (message: string) => void) => ipcRenderer.on('log', (_event, message) => listener(message)),
  packages: () => ipcRenderer.invoke('packages'),
  search: (query: string, managers: string[]) => ipcRenderer.invoke('search', query, managers),
  skip: (key: string, version: string) => ipcRenderer.invoke('skip', key, version),
  history: () => ipcRenderer.invoke('history'),
  exportLogs: () => ipcRenderer.invoke('export-logs'),
  openRunLogs: () => ipcRenderer.invoke('open-run-logs'),
  queue: () => ipcRenderer.invoke('queue'),
  queueAdd: (action: string, packages: unknown[]) => ipcRenderer.invoke('queue-add', action, packages),
  queueCancel: (id: number) => ipcRenderer.invoke('queue-cancel', id),
  queueRetry: (id: number) => ipcRenderer.invoke('queue-retry', id),
  queueClear: () => ipcRenderer.invoke('queue-clear'),
  queueLog: (id: number) => ipcRenderer.invoke('queue-log', id),
  onQueue: (listener: (operations: unknown[]) => void) => ipcRenderer.on('queue', (_event, operations) => listener(operations)),
  onPackageDone: (listener: (done: unknown) => void) => ipcRenderer.on('package-done', (_event, done) => listener(done)),
  onInventory: (listener: (inventory: unknown) => void) => ipcRenderer.on('inventory', (_event, inventory) => listener(inventory)),
  onCheckRequested: (listener: () => void) => ipcRenderer.on('check-requested', () => listener()),
  managers: () => ipcRenderer.invoke('managers'),
  sources: (manager: string) => ipcRenderer.invoke('sources', manager),
  sourceChange: (manager: string, change: string, name: string, url: string) => ipcRenderer.invoke('source-change', manager, change, name, url),
  details: (entry: unknown) => ipcRenderer.invoke('details', entry),
  icons: (packages: unknown[]) => ipcRenderer.invoke('icons', packages),
  openUrl: (url: string) => ipcRenderer.invoke('open-url', url),
  openApp: (entry: unknown) => ipcRenderer.invoke('open-app', entry),
  setOptions: (key: string, options: unknown) => ipcRenderer.invoke('options-set', key, options),
  bundleOpen: () => ipcRenderer.invoke('bundle-open'),
  bundleSave: (packages: unknown[], incompatible: unknown[]) => ipcRenderer.invoke('bundle-save', packages, incompatible),
  bundleInstall: (packages: unknown[]) => ipcRenderer.invoke('bundle-install', packages),
  bundleInstalled: () => ipcRenderer.invoke('bundle-installed'),
  backupNow: () => ipcRenderer.invoke('backup-now'),
  backupFolder: () => ipcRenderer.invoke('backup-folder'),
  backupOpenFolder: () => ipcRenderer.invoke('backup-open-folder'),
  gistToken: (token: string) => ipcRenderer.invoke('gist-token', token),
  gistForget: () => ipcRenderer.invoke('gist-forget'),
  gistState: () => ipcRenderer.invoke('gist-state'),
  gistRestore: () => ipcRenderer.invoke('gist-restore'),
  onSelfReady: (listener: (version: string) => void) => ipcRenderer.on('self-ready', (_event, version) => listener(version)),
});
